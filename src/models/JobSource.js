import mongoose from "mongoose";

const JobSourceSchema = new mongoose.Schema(
  {
    key: { type: String, required: true, unique: true, index: true },
    displayName: { type: String, required: true },
    adapterModule: { type: String, default: "" },
    enabled: { type: Boolean, default: false, index: true },
    approved: { type: Boolean, default: false },
    termsUrl: { type: String, required: true },
    attributionText: { type: String, required: true },
    attributionUrl: { type: String, required: true },
    retentionDays: { type: Number, required: true, min: 1 },
    staleAfterDays: { type: Number, required: true, min: 1 },
    quota: {
      requestsPerDay: { type: Number, required: true, min: 1 },
      intervalMs: { type: Number, required: true, min: 60000 },
      timeoutMs: { type: Number, default: 10000, min: 1000, max: 30000 },
      maxRetries: { type: Number, default: 2, min: 0, max: 3 },
      limits: {
        perMinute: { type: Number, min: 1 },
        perDay: { type: Number, min: 1 },
        perWeek: { type: Number, min: 1 },
        perMonth: { type: Number, min: 1 },
      },
    },
    termsVerifiedAt: { type: Date, required: true },
    commercialLicenseReference: { type: String, default: "" },
    attributionBadgeVerified: { type: Boolean, default: false },
    storageDisplayTermsReviewed: { type: Boolean, default: false },
    cursor: { type: String, default: null },
    demandCursor: { type: Number, default: 0, min: 0 },
    demandTerm: { type: String, default: null },
    conditionalQuery: { type: String, default: "__all__" },
    etag: { type: String, default: null },
    lastModified: { type: String, default: null },
    quotaWindowStart: { type: Date, default: () => new Date(0) },
    quotaUsed: { type: Number, default: 0, min: 0 },
    quotaMinuteStart: { type: Date, default: () => new Date(0) },
    quotaMinuteUsed: { type: Number, default: 0, min: 0 },
    quotaWeekStart: { type: Date, default: () => new Date(0) },
    quotaWeekUsed: { type: Number, default: 0, min: 0 },
    quotaMonthStart: { type: Date, default: () => new Date(0) },
    quotaMonthUsed: { type: Number, default: 0, min: 0 },
    lastRequestAt: { type: Date, default: null },
    lastRunAt: { type: Date, default: null },
    runLeaseExpiresAt: { type: Date, default: null },
    lastSuccessAt: { type: Date, default: null },
    lastFullSyncAt: { type: Date, default: null },
    lastLinkCheckAt: { type: Date, default: null },
    runState: { type: String, enum: ["idle", "running", "healthy", "degraded", "disabled"], default: "idle" },
    circuit: {
      failures: { type: Number, default: 0 },
      openUntil: { type: Date, default: null },
    },
    metrics: {
      fetched: { type: Number, default: 0 },
      created: { type: Number, default: 0 },
      updated: { type: Number, default: 0 },
      duplicates: { type: Number, default: 0 },
      errors: { type: Number, default: 0 },
      latencyMs: { type: Number, default: 0 },
      countryCounts: { type: Map, of: Number, default: {} },
      occupationCounts: { type: Map, of: Number, default: {} },
    },
    lastErrorCode: { type: String, default: "" },
  },
  { timestamps: true, minimize: false },
);

export const JobSource = mongoose.models.JobSource || mongoose.model("JobSource", JobSourceSchema);
