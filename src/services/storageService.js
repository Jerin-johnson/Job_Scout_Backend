import {
  S3Client,
  PutObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  DeleteObjectCommand,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { env } from "../config/env.js";
import { logger } from "../shared/utils/logger.js";

let s3Client = null;

function isRealCredential(value) {
  return (
    typeof value === "string" &&
    value.trim() !== "" &&
    !/dummy|replace.?me|your.?key|changeme/i.test(value)
  );
}

/**
 * Explicit credentials are optional: when absent, AWS SDK v3 uses its default
 * credential provider chain (environment, shared config, workload role, etc.).
 * @param {typeof env} config
 */
export function createS3ClientOptions(config = env) {
  const hasAccessKey = isRealCredential(config.S3_ACCESS_KEY_ID);
  const hasSecretKey = isRealCredential(config.S3_SECRET_ACCESS_KEY);
  if (hasAccessKey !== hasSecretKey) {
    const error = new Error(
      "Both S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY must be configured together.",
    );
    error.statusCode = 503;
    error.code = "STORAGE_CONFIGURATION_INVALID";
    throw error;
  }

  return {
    region: config.S3_REGION,
    ...(config.S3_ENDPOINT ? { endpoint: config.S3_ENDPOINT } : {}),
    ...(hasAccessKey
      ? {
          credentials: {
            accessKeyId: config.S3_ACCESS_KEY_ID,
            secretAccessKey: config.S3_SECRET_ACCESS_KEY,
          },
        }
      : {}),
  };
}

export function isMockStorageEnabled(config = env) {
  return (
    config.NODE_ENV !== "production" &&
    config.AI_ALLOW_MOCKS &&
    !isRealCredential(config.S3_ACCESS_KEY_ID) &&
    !isRealCredential(config.S3_SECRET_ACCESS_KEY)
  );
}

function storageError(code, message) {
  const error = new Error(message);
  error.statusCode = 503;
  error.code = code;
  return error;
}

function getS3Client() {
  if (s3Client) return s3Client;
  s3Client = new S3Client(createS3ClientOptions());
  return s3Client;
}

export const storageService = {
  /**
   * Create a short-lived, content-type-bound URL for a browser-to-S3 upload.
   * The caller supplies an opaque, user-scoped object key generated by the API.
   */
  async createPresignedUpload({ key, contentType, expiresInSeconds = 300 }) {
    if (!env.S3_BUCKET?.trim()) {
      throw storageError("STORAGE_NOT_CONFIGURED", "Resume file storage is not configured.");
    }
    if (isMockStorageEnabled()) {
      throw storageError(
        "STORAGE_PRESIGNED_UNAVAILABLE",
        "Direct S3 uploads are disabled while local mock storage is active.",
      );
    }

    try {
      const uploadUrl = await getSignedUrl(
        getS3Client(),
        new PutObjectCommand({
          Bucket: env.S3_BUCKET,
          Key: key,
          ContentType: contentType,
        }),
        { expiresIn: expiresInSeconds },
      );
      return { uploadUrl, requiredHeaders: { "Content-Type": contentType } };
    } catch (err) {
      logger.error(
        { errorName: err?.name, errorCode: err?.code },
        "Failed to sign S3 resume upload",
      );
      throw storageError("STORAGE_UNAVAILABLE", "Resume file storage is temporarily unavailable.");
    }
  },

  async getObjectMetadata({ key }) {
    try {
      const metadata = await getS3Client().send(
        new HeadObjectCommand({ Bucket: env.S3_BUCKET, Key: key }),
      );
      return {
        contentLength: metadata.ContentLength,
        contentType: metadata.ContentType,
        etag: metadata.ETag,
      };
    } catch (err) {
      logger.error(
        { errorName: err?.name, errorCode: err?.code },
        "Failed to verify uploaded S3 object",
      );
      if (err?.$metadata?.httpStatusCode === 404 || err?.name === "NotFound") {
        const missing = new Error("The uploaded resume could not be found. Upload it again.");
        missing.statusCode = 404;
        missing.code = "RESUME_UPLOAD_NOT_FOUND";
        throw missing;
      }
      throw storageError("STORAGE_UNAVAILABLE", "Uploaded resume could not be verified in storage.");
    }
  },

  /**
   * Upload original file to S3 / Cloudflare R2. Resume text is encrypted
   * separately before it is stored in the database.
   */
  async uploadFile({ key, buffer, contentType }) {
    if (!env.S3_BUCKET?.trim()) {
      throw storageError("STORAGE_NOT_CONFIGURED", "Resume file storage is not configured.");
    }

    if (isMockStorageEnabled()) {
      logger.debug("Mock storage mode active; no original file is persisted");
      return `s3://${env.S3_BUCKET}/${key}`;
    }

    try {
      const client = getS3Client();
      await client.send(
        new PutObjectCommand({
          Bucket: env.S3_BUCKET,
          Key: key,
          Body: buffer,
          ContentType: contentType,
        }),
      );
      return `s3://${env.S3_BUCKET}/${key}`;
    } catch (err) {
      // Do not log object keys: they contain user identifiers and file hashes.
      logger.error(
        { errorName: err?.name, errorCode: err?.code },
        "Failed to upload file to S3/R2",
      );
      throw storageError("STORAGE_UNAVAILABLE", "Resume file storage is temporarily unavailable.");
    }
  },

  /**
   * Download file from S3 / R2
   */
  async getFile({ key, etag }) {
    if (isMockStorageEnabled()) {
      return Buffer.from("");
    }

    try {
      const client = getS3Client();
      const response = await client.send(
        new GetObjectCommand({
          Bucket: env.S3_BUCKET,
          Key: key,
          ...(etag ? { IfMatch: etag } : {}),
        }),
      );

      const byteArray = await response.Body.transformToByteArray();
      return Buffer.from(byteArray);
    } catch (err) {
      logger.error(
        { errorName: err?.name, errorCode: err?.code },
        "Failed to download file from S3/R2",
      );
      throw storageError("STORAGE_UNAVAILABLE", "Resume file storage is temporarily unavailable.");
    }
  },

  async deleteFile({ key }) {
    if (!env.S3_BUCKET?.trim()) {
      if (isMockStorageEnabled()) return;
      throw storageError("STORAGE_NOT_CONFIGURED", "Resume file storage is not configured.");
    }
    if (isMockStorageEnabled()) return;
    try {
      await getS3Client().send(new DeleteObjectCommand({ Bucket: env.S3_BUCKET, Key: key }));
    } catch (err) {
      logger.error({ errorName: err?.name, errorCode: err?.code }, "Failed to delete stored resume file");
      throw storageError("STORAGE_UNAVAILABLE", "Resume file could not be removed from storage.");
    }
  },
};
